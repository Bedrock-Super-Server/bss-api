//! Generates, for a plugin built to WebAssembly, the functions of `HostApi` as imports of the
//! module `bss`, which the server provides with the same signatures.

use std::fmt::Write as _;
use std::path::PathBuf;

include!("build/abi.rs");

fn main() {
    println!("cargo:rerun-if-changed=build/abi.rs");
    println!("cargo:rerun-if-changed=src/ffi/host.rs");
    if std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() != Ok("wasm32") {
        return;
    }
    let source = std::fs::read_to_string("src/ffi/host.rs").expect("src/ffi/host.rs");
    let functions = host_functions(&source);

    let mut out = String::from(
        "// Generated by build.rs from src/ffi/host.rs.\n\n#[link(wasm_import_module = \"bss\")]\nunsafe extern \"C\" {\n",
    );
    for function in &functions {
        let params: Vec<String> = function
            .params
            .iter()
            .map(|(name, ty)| format!("{name}: {ty}"))
            .collect();
        let ret = function
            .ret
            .as_ref()
            .map(|ret| format!(" -> {ret}"))
            .unwrap_or_default();
        writeln!(out, "    fn {}({}){ret};", function.name, params.join(", ")).unwrap();
    }
    out.push_str("}\n\n/// The table of the functions the server says it provides to this plugin.\npub(crate) fn table(has: impl Fn(&str) -> bool) -> HostApi {\n    HostApi {\n        header: crate::ffi::version::HostHeader::of::<HostApi>(),\n");
    for function in &functions {
        writeln!(
            out,
            "        {0}: if has(\"{0}\") {{ Some({0}) }} else {{ None }},",
            function.name
        )
        .unwrap();
    }
    out.push_str("    }\n}\n");

    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("wasm_host.rs");
    std::fs::write(path, out).expect("write wasm_host.rs");
}
